#!/usr/bin/env python3
"""Export the 5x7 bitmap font (with Polish letters) from python/act1033led/font.py to
src/font_js.h, which the ESP serves to the web page as /font.js.

Usage: python gen_font.py   (no third-party packages needed)
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "python"))
from act1033led import font  # noqa: E402

glyphs = {ch: [w, [[y, rows[y]] for y in sorted(rows)]] for ch, (w, rows) in font.GLYPHS.items()}
js = ("const FONT=" + json.dumps(glyphs, ensure_ascii=True, separators=(",", ":")) + ";\n"
      "const FONT_BASE=" + json.dumps(font.BASE, ensure_ascii=True, separators=(",", ":")) + ";\n")
out = root / "esp32" / "src" / "font_js.h"
out.write_text('#pragma once\n#include <Arduino.h>\n// generated by tools/gen_font.py\n'
               'static const char FONT_JS[] PROGMEM = R"JS(' + js + ')JS";\n', encoding="utf-8")
print("glyphs:", len(glyphs), "bytes:", len(js), "->", out)
