"""Generate src/mpk_font.h (ASCII 32..126, 5x7 proportional) from the browser font in src/font_js.h."""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1] / "src"
js = (root / "font_js.h").read_text(encoding="utf-8")
font = json.loads(re.search(r"const FONT=(\{.*?\});\n", js, re.S).group(1))

out = ["#pragma once", "// generated by tools/gen_mpk_font.py - 5x7 glyphs for ASCII 32..126 (bit 4 = leftmost pixel)",
       "#include <stdint.h>", "struct MpkGlyph { uint8_t w; uint8_t r[7]; };",
       "static const MpkGlyph MPK_FONT[95] = {"]
for code in range(32, 127):
    ch = chr(code)
    w, rows = font.get(ch, font["?"])
    r = [0] * 7
    for y, bits in rows:
        if 0 <= y < 7:
            r[y] = sum(1 << (4 - i) for i, c in enumerate(bits) if c == "#")
    out.append("  {%d,{%s}},  // %r" % (w, ",".join("0x%02X" % v for v in r), ch))
out.append("};")
(root / "mpk_font.h").write_text("\n".join(out) + "\n", encoding="utf-8")
