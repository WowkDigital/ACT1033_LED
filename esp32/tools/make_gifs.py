#!/usr/bin/env python3
"""Generate the built-in 64x16 demo GIFs (shared 16-colour palette, see docs/PROTOCOL.md)
and write them as src/gifs.h plus tools/gif_a.gif and tools/gif_b.gif.

Usage: python make_gifs.py   (requires Pillow)
"""
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw

W, H = 64, 16
PALETTE = [(0, 0, 0), (0, 90, 0), (90, 0, 0), (0, 0, 90), (90, 90, 0), (90, 0, 90), (0, 90, 90),
           (90, 90, 90), (0, 40, 0), (40, 0, 0), (0, 0, 40), (40, 40, 0), (40, 0, 40), (0, 40, 40),
           (40, 40, 40), (120, 120, 120)]


def pal_image():
    p = Image.new("P", (1, 1))
    p.putpalette([c for rgb in PALETTE for c in rgb])  # exactly 16 entries -> global table of 16
    return p


def save(frames, duration):
    pal = pal_image()
    q = [f.quantize(palette=pal, dither=Image.Dither.NONE) for f in frames]
    buf = BytesIO()
    q[0].save(buf, format="GIF", save_all=True, append_images=q[1:], duration=duration, loop=0, optimize=False)
    return buf.getvalue()


def gif_a():
    """A green bar sweeps to the right; white lines at the top and bottom."""
    frames = []
    for i in range(32):
        im = Image.new("RGB", (W, H), PALETTE[0])
        d = ImageDraw.Draw(im)
        x = int(i * (W - 8) / 31)
        d.rectangle([x, 2, x + 7, H - 3], fill=PALETTE[1])
        d.rectangle([0, 0, W - 1, 0], fill=PALETTE[15])
        d.rectangle([0, H - 1, W - 1, H - 1], fill=PALETTE[15])
        frames.append(im)
    return save(frames, 80)


def gif_b():
    """A blinking red/blue checkerboard."""
    frames = []
    for i in range(8):
        im = Image.new("RGB", (W, H), PALETTE[0])
        px = im.load()
        for y in range(H):
            for x in range(W):
                if ((x // 4) + (y // 4) + i // 4) % 2 == 0:
                    px[x, y] = PALETTE[2] if (i % 2 == 0) else PALETTE[3]
        frames.append(im)
    return save(frames, 250)


def check(gif):
    gct = 2 << (gif[10] & 7) if gif[10] & 0x80 else 0
    print("  global table:", gct, "size:", len(gif))


def c_array(name, data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]))
    return (f"const uint8_t {name}[] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n"
            f"const size_t {name}_len = {len(data)};\n")


if __name__ == "__main__":
    a, b = gif_a(), gif_b()
    check(a), check(b)
    out = Path(__file__).resolve().parents[1] / "src" / "gifs.h"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// generated by tools/make_gifs.py\n#pragma once\n#include <Arduino.h>\n"
                   + c_array("GIF_A", a) + c_array("GIF_B", b))
    Path(__file__).with_name("gif_a.gif").write_bytes(a)
    Path(__file__).with_name("gif_b.gif").write_bytes(b)
    print("ok ->", out)
