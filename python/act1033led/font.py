_ACUTE = (0, "...#./..#..")        # lower case (rows 0-1)
_ACUTE_UP = (-2, "...#./..#..")    # upper case (rows -2..-1)
_DOT = (0, "..#..")                # ż
_DOT_UP = (-1, "..#..")            # Ż
_OGONEK = (7, "...#./...##")


def _parse(spec):
    y0, rows = spec
    rows = rows.split("/")
    width = max(len(r) for r in rows)
    return width, {y0 + i: r.ljust(width, ".") for i, r in enumerate(rows)}


GLYPHS: dict[str, tuple[int, dict[int, str]]] = {ch: _parse(s) for ch, s in _RAW.items()}


def _compose(base: str, *overlays):
    w, rows = GLYPHS[base]
    rows = dict(rows)
    for ov in overlays:
        ow, orows = _parse(ov)
        w = max(w, ow)
        for y, r in orows.items():
            cur = rows.get(y, "." * w)
            r = r.ljust(w, ".")
            cur = cur.ljust(w, ".")
            rows[y] = "".join("#" if "#" in (a, b) else "." for a, b in zip(cur, r))
    return w, rows


